import { isDemoEngine } from "@/lib/ai-provenance";
import { cn } from "@/lib/utils";

/**
 * Structural provenance marker: renders when no real model produced the output.
 *
 * Mirrors the `DataFreshness` chip — same muted treatment, deliberately quieter
 * than the amber it sits inside. Amber marks inference; this marks who inferred.
 *
 * Fails closed (see `isDemoEngine`): renders unless a known real provider is
 * named, and disappears on its own once one is configured. Call sites pass
 * `AiResult.provider` through and never decide this themselves.
 */
export function DemoEngineChip({ provider, className }: { provider?: string; className?: string }) {
  if (!isDemoEngine(provider)) return null;
  return (
    <span
      className={cn(
        "inline-flex items-center gap-1.5 rounded-full border border-line bg-surface px-2.5 py-1 font-mono text-micro uppercase tracking-[0.12em] text-ink-3",
        className,
      )}
      title="Generated by the FootIQ demo engine, not a live AI model. It disappears once a real provider is configured."
    >
      <span className="size-1.5 rounded-full bg-ink-3" aria-hidden />
      Demo engine
    </span>
  );
}
